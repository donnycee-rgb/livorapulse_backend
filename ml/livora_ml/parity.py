"""Test cases that keep the API's forecast identical to Python's.

    python -m livora_ml.parity        # rewrite tests/fixtures/forecast_parity.json

The API (src/services/MoodForecast.ts) repeats the forecast step with each
user's saved model. This writes saved models, inputs and the forecasts
Python gives; a Node test (test/moodForecast.test.ts) must reproduce them,
and a pytest checks this file is up to date with the Python code.
"""
from __future__ import annotations

import json
from datetime import date, timedelta
from pathlib import Path

from .features import build_user
from .model import fit, forecast_from_params, user_params
from .simulate import simulate

FIXTURE = Path(__file__).resolve().parents[1] / "tests" / "fixtures" / "forecast_parity.json"
ROW_KEYS = ("sleepMinutes", "steps", "screenMinutes", "socialMinutes", "focusMinutes", "waterGlasses", "moodValue")


def _row(r):
    return None if r is None else {k: r.get(k) for k in ROW_KEYS}


def build() -> dict:
    sims = simulate(30, 60, seed=99, start=date(2026, 9, 1))
    result = fit({s.id: build_user(s.rows) for s in sims})
    cases = []
    for s in sims[:4]:
        post = result.users[s.id]
        params = user_params(result.population, post)
        by_date = {r["date"]: r for r in s.rows}
        last = max(by_date)
        d = last + timedelta(days=1)  # forecast the day after the data
        yday = by_date[last]
        variants = [
            ("last night's sleep logged", {"sleepMinutes": 410}, yday),
            ("short night", {"sleepMinutes": 240}, yday),
            ("nothing logged today", None, yday),
            ("nothing logged yesterday either", None, None),
            ("yesterday partly logged", {"sleepMinutes": 480}, {"steps": 9000, "moodValue": None}),
        ]
        for name, today_row, yday_row in variants:
            fc = forecast_from_params(params, today_row, yday_row, d)
            cases.append({
                "name": f"{s.id}: {name}", "date": d.isoformat(), "params": params,
                "today": _row(today_row), "yesterday": _row(yday_row),
                "expected": {"mean": fc.mean, "lower": fc.lower, "upper": fc.upper},
            })
    # A weekend day, to check the weekday rule matches
    s = sims[0]
    post = result.users[s.id]
    params = user_params(result.population, post)
    sat = date(2026, 11, 14)
    assert sat.weekday() == 5
    fc = forecast_from_params(params, {"sleepMinutes": 500}, None, sat)
    cases.append({"name": "weekend", "date": sat.isoformat(), "params": params, "today": {"sleepMinutes": 500},
                  "yesterday": None, "expected": {"mean": fc.mean, "lower": fc.lower, "upper": fc.upper}})
    return {"note": "Generated by python -m livora_ml.parity. Do not edit.", "cases": cases}


def main() -> None:
    FIXTURE.parent.mkdir(parents=True, exist_ok=True)
    FIXTURE.write_text(json.dumps(build(), indent=1) + "\n", encoding="utf-8")
    print(f"wrote {FIXTURE}")


if __name__ == "__main__":
    main()
